/**
 * Email a newly dispatched field technician the job details. Best-effort:
 * silently no-ops if email isn't configured or the technician can't be found.
 */
async function notifyTechnicianAssigned(
  technicianId: string,
  lead: Awaited<ReturnType<typeof getSubmission>>
): Promise<void> {
  if (!isEmailConfigured() || !lead) return;
  const tech = await getTechnician(technicianId);
  if (!tech || !tech.email) return;

  const when = lead.jobAt || lead.inspectionAt;
  const whenLabel = lead.jobAt ? "Job" : lead.inspectionAt ? "Inspection" : "";
  const rows: string[] = [];
  if (lead.name) rows.push(`<p><b>Customer:</b> ${lead.name}</p>`);
  if (lead.address) rows.push(`<p><b>Address:</b> ${lead.address}</p>`);
  if (lead.phone) rows.push(`<p><b>Phone:</b> ${lead.phone}</p>`);
  if (lead.service) rows.push(`<p><b>Service:</b> ${lead.service}</p>`);
  if (when) {
    rows.push(`<p><b>${whenLabel} time:</b> ${formatAppt(when, { weekday: "long", day: "2-digit", month: "short", year: "numeric", hour: "numeric", minute: "2-digit", hour12: true }) || when}</p>`);
  }

  const logoUrl = await getEmailLogoUrl();
  await sendEmail({
    toEmail: tech.email,
    subject: `New Groutix assignment${lead.address ? ` — ${lead.address}` : ""}`,
    html: wrapEmailHtml(
      `<h2 style="margin:0 0 12px">You've been assigned a job</h2>
       <p>Hi ${tech.name}, you've been dispatched to the following:</p>
       ${rows.join("\n")}
       <p style="margin-top:16px;color:#64748b">Please review the details and be on site on time.</p>`,
      "You've been assigned a new Groutix job",
      logoUrl
    ),
  });
}

export async function GET(_req: NextRequest, { params }: Ctx) {
  if (!isMongoConfigured()) {
    return NextResponse.json({ error: "Database is not configured." }, { status: 503 });
  }
  const { id } = await params;
  const item = await getSubmission(id);
  if (!item) return NextResponse.json({ error: "Not found." }, { status: 404 });
  return NextResponse.json({ item });
}

export async function PATCH(req: NextRequest, { params }: Ctx) {
  if (!isMongoConfigured()) {
    return NextResponse.json({ error: "Database is not configured." }, { status: 503 });
  }
  const { id } = await params;
  let body: Record<string, any>;
  try {
    body = await req.json();
  } catch {
    return NextResponse.json({ error: "Invalid request." }, { status: 400 });
  }
  if (!body || typeof body !== "object" || Array.isArray(body)) {
    return NextResponse.json({ error: "Invalid request." }, { status: 400 });
  }

  const appendBooking = body.appendBooking === true;
  const bookingOriginalStart = typeof body.bookingOriginalStart === "string" ? body.bookingOriginalStart : undefined;
  const bookingId = typeof body.bookingId === "string" ? body.bookingId : undefined;
  delete body.bookingId;
  delete body.appendBooking;
  delete body.bookingOriginalStart;
  delete body.bookings;
  delete body.activeBooking;
  // Dispatch explicitly opts in after the dispatcher reviews the booking.
  const bookingNotifications = body.bookingNotifications === true;
  delete body.bookingNotifications;
  // Occupied daily windows are generated by the server, never accepted from clients.
  delete body.jobWorkSegments;
  delete body.inspectionWorkSegments;
  const notificationWarnings: string[] = [];

  // Quote editing does not change appointments or trigger workflow notifications.
  // Persist directly instead of loading the complete lead and booking/zone settings.
  const quoteFields = new Set([
    "quoteScope", "quoteItems", "quoteTaxMode", "quoteTaxRate", "quoteTerms", "quoteAmount", "quoteUpdated",
    "name", "phone", "email", "address", "customerType", "agency", "tenants",
  ]);
  const fields = Object.keys(body);
  if (fields.some(field => field.startsWith("quote")) && fields.every(field => quoteFields.has(field))) {
    try {
      const saved = await updateSubmission(id, body);
      return saved ? NextResponse.json({ ok: true }) : NextResponse.json({ error: "Quote could not be saved. The lead may no longer exist." }, { status: 404 });
    } catch (error) {
      console.error("Quote save failed:", error);
      return NextResponse.json({ error: "Could not save the quote. Please try again." }, { status: 503 });
    }
  }

  // Snapshot the prior state so we can record what actually changed.
  const current = await getSubmission(id);
  const before = current ? { ...current } : null;
  if (!before) return NextResponse.json({ error: "Not found." }, { status: 404 });

  // Receipt fields are server-owned snapshots of the saved invoice.
  delete body.paymentReceipt;
  delete body.receiptSentAt;
  if (body.paymentType === "full") {
    try {
      body.paymentReceipt = before.paymentReceipt || receiptFromInvoice(before);
      body.amountPaid = body.paymentReceipt.total;
      body.invoiceStatus = "Paid";
    } catch (error) {
      return NextResponse.json({ error: (error as Error).message }, { status: 400 });
    }
  }

  // Lost is an archive action, not a workflow transition. Move the saved
  // snapshot without changing its status, visit progress, or completion flags.
  if (body.status === "Lost") {
    const session = await verifySession(req.cookies.get(SESSION_COOKIE)?.value);
    const moved = await deleteSubmission(id, session?.username || "staff");
    if (!moved) return NextResponse.json({ error: "Not found." }, { status: 404 });
    await deleteBooking(id);
    return NextResponse.json({ ok: true, recycled: true });
  }

  if (appendBooking && ["Lost", "Cancelled"].includes(before.status)) return NextResponse.json({ error: "Reopen this lead before adding a booking." }, { status: 409 });
  const primary = { ...before };
  const bookingType = "jobAt" in body ? "job" : "inspectionAt" in body ? "inspection" : undefined;
  if (appendBooking && !bookingType) return NextResponse.json({ error: "Choose a booking type." }, { status: 400 });
  let selectedBookingId: string | undefined;
  let secondaryVisit = false;
  if (bookingType && (appendBooking || bookingOriginalStart || bookingId)) {
    const startField = bookingType === "job" ? "jobAt" : "inspectionAt";
    const endField = bookingType === "job" ? "jobEndAt" : "inspectionEndAt";
    const segmentsField = bookingType === "job" ? "jobWorkSegments" : "inspectionWorkSegments";
    if (appendBooking) {
      // Adding a visit must never overwrite customer details, finance or workflow.
      const allowed = new Set([startField, endField, ...(bookingType === "job"
        ? ["technicianId", "technician", "technicianUsername"] : ["inspectorId", "assigned", "inspectorUsername"])]);
      for (const key of Object.keys(body)) if (!allowed.has(key)) delete body[key];
      before[startField] = undefined;
      before[endField] = undefined;
      before[segmentsField] = undefined;
      if (!primary[startField]) body.status = bookingType === "job" ? "Job Booked" : "Inspection Booked";
    } else {
      const matches = before.bookings?.filter(b => b.type === bookingType && (bookingId ? b.bookingId === bookingId : `${b.date}T${b.time}` === bookingOriginalStart)) || [];
      if (bookingId && matches.length !== 1 || !bookingId && matches.length > 1) return NextResponse.json({ error: "Select the specific booking before editing." }, { status: 409 });
      const booking = matches[0];
      if (!booking && bookingOriginalStart !== primary[startField]?.slice(0, 16)) return NextResponse.json({ error: "This booking has changed. Refresh before editing." }, { status: 409 });
      if (booking) {
        selectedBookingId = booking.bookingId;
        const primaryBooking = before.bookings?.find(b => b.type === bookingType && isPrimaryBooking(primary, b));
        secondaryVisit = booking.bookingId ? booking.bookingId !== primaryBooking?.bookingId : bookingOriginalStart !== primary[startField]?.slice(0, 16);
        before[startField] = `${booking.date}T${booking.time}`;
        before[endField] = booking.endAt;
        before[segmentsField] = booking.workSegments;
        if (bookingType === "job") Object.assign(before, { technician: booking.technician, technicianId: booking.technicianId, technicianUsername: booking.technicianUsername });
        else Object.assign(before, { assigned: booking.assigned, inspectorId: booking.inspectorId, inspectorUsername: booking.inspectorUsername });
      }
    }
  }

  if (typeof body.status === "string" && body.status !== before.status) {
    const isTerminal = /^(lost|cancelled|closed|no response)/i.test(body.status);
    const wasTerminal = /^(lost|cancelled|closed|no response)/i.test(before.status || "");
    if (isTerminal && !wasTerminal) {
      body.previousStatus = before.previousStatus || before.status || "New";
    }
  }

  // Acquire new slot locks before changing the lead. A conflict must never
  // overwrite the prior appointment or trigger a reschedule notification.
  // A name-only reassignment must not retain the previous person's ID.
  if ("assigned" in body && body.assigned !== before.assigned && !("inspectorId" in body)) { body.inspectorId = ""; body.inspectorUsername = ""; }
  if ("technician" in body && body.technician !== before.technician && !("technicianId" in body)) {
    body.technicianId = "";
    body.technicianUsername = "";
  }
  if ("technicianId" in body && body.technicianId !== before.technicianId && !("technicianUsername" in body)) body.technicianUsername = "";
  if ("inspectorId" in body && body.inspectorId !== before.inspectorId && !("inspectorUsername" in body)) body.inspectorUsername = "";
  const inspectorChanged = ["inspectorId", "assigned", "inspectorUsername"].some(key => key in body && body[key] !== before[key as keyof typeof before]);
  if (inspectorChanged && before.inspectionAt && !("inspectionAt" in body)) body.inspectionAt = before.inspectionAt;
  const assignmentChanged = ["technicianId", "technician", "technicianUsername"].some((key) => key in body && body[key] !== before[key as keyof typeof before]);
  if (assignmentChanged && before.jobAt && !("jobAt" in body)) body.jobAt = before.jobAt;
  for (const type of ["inspection", "job"] as const) {
    const startField = type === "job" ? "jobAt" : "inspectionAt";
    const endField = type === "job" ? "jobEndAt" : "inspectionEndAt";
    if (endField in body && !(startField in body)) body[startField] = before[startField];
    if (startField in body && !body[startField]) {
      body[endField] = "";
      body[type === "job" ? "jobWorkSegments" : "inspectionWorkSegments"] = [];
    }
    // Older editing screens supply only a new start; preserve working hours.
    if (typeof body[startField] === "string" && body[startField] && before[startField] && before[endField] && !(endField in body)) {
      try {
        const rules = staffBookingRules(await getBookingRules());
        const stored = type === "job" ? before.jobWorkSegments : before.inspectionWorkSegments;
        const minutes = (stored?.length ? stored : bookingSegments(type, before[startField]!.slice(0, 16), before[endField]!, rules)).reduce((sum, segment) => sum + segment.scheduledMinutes, 0);
        body[endField] = bookingEndForDuration(type, body[startField].slice(0, 16), minutes, rules);
      } catch (error) { return NextResponse.json({ error: error instanceof Error ? error.message : "Invalid booking time." }, { status: 400 }); }
    }
  }
  const reserved: { type: "inspection" | "job"; date: string; time: string; reservationId?: string; previousBooking?: BookingDoc }[] = [];
  const rollback = async () => {
    await Promise.all(reserved.map((slot) => releaseBookingSlot(id, slot.type, slot.date, slot.time, slot)));
  };
  try {
    for (const type of ["inspection", "job"] as const) {
      const field = type === "inspection" ? "inspectionAt" : "jobAt";
      if (!(field in body)) continue;
      // An empty date field may arrive as null from older lead records/forms.
      // Canonicalise it to the same empty string used by the clear-booking UI.
      if (body[field] == null) body[field] = "";
      if (typeof body[field] !== "string") {
        await rollback();
        return NextResponse.json({ error: "Invalid appointment." }, { status: 400 });
      }
      if (!body[field].trim()) { body[field] = ""; continue; }
      const value = normalizeApptString(body[field]);
      const match = /^(\d{4}-\d{2}-\d{2})T([01]\d|2[0-3]):([0-5]\d)/.exec(value || "");
      if (!match || !validScheduleDate(match[1])) {
        await rollback();
        return NextResponse.json({ error: "Invalid appointment date or time." }, { status: 400 });
      }
      body[field] = value;
      const endField = type === "job" ? "jobEndAt" : "inspectionEndAt";
      if (value === normalizeApptString(before[field]) && (!(endField in body) || body[endField] === before[endField]) && !(type === "job" ? assignmentChanged : inspectorChanged)) continue;
      const scheduledMinutes = before[field] ? savedLeadBookingMinutes(before, type) : (await getBookingRules())[type].slotMinutes;
      let endAt = body[endField] || before[endField];
      try { endAt ||= bookingEndForDuration(type, value!, scheduledMinutes, staffBookingRules(await getBookingRules())); }
      catch (error) { await rollback(); return NextResponse.json({ error: error instanceof Error ? error.message : "Invalid working hours." }, { status: 400 }); }
      body[endField] = endAt;
      const segmentsField = type === "job" ? "jobWorkSegments" : "inspectionWorkSegments";
      if (endAt) {
        try { body[segmentsField] = bookingSegments(type, value!, endAt, staffBookingRules(await getBookingRules())); }
        catch (error) { await rollback(); return NextResponse.json({ error: error instanceof Error ? error.message : "Invalid end time." }, { status: 400 }); }
      }
      else body[segmentsField] = [];
      if ((value === normalizeApptString(before[field]) && endAt === before[endField] && !(type === "job" ? assignmentChanged : inspectorChanged)) || ["Lost", "Cancelled"].includes(body.status || before.status)) continue;
      const date = match[1];
      const time = `${match[2]}:${match[3]}`;
      const area = resolveArea((body.address ?? before.address) || (body.city ?? before.city), await getZoneRules());
      if (!endAt) body[segmentsField] = [{ date, time, scheduledMinutes }];
      const result = await createBooking({ leadId: id, type, date, time, endAt, scheduledMinutes, zone: area.zone,
        ...(type === "job" ? {
          technicianId: body.technicianId ?? before.technicianId,
          technician: body.technician ?? before.technician,
          technicianUsername: body.technicianUsername ?? before.technicianUsername,
        } : { inspectorId: body.inspectorId ?? before.inspectorId, assigned: body.assigned ?? before.assigned, inspectorUsername: body.inspectorUsername ?? before.inspectorUsername }),
        suburb: area.suburb || undefined, reference: primary.jobNo || `GX-ADM-${id.slice(-6)}` }, { retainPrevious: true, staffOverride: true, append: appendBooking, bookingId: type === bookingType && selectedBookingId ? selectedBookingId : primary.bookings?.find(b => b.type === type && isPrimaryBooking(primary, b))?.bookingId, replaceStart: before[field]?.slice(0, 16) });
      if (!result.ok) {
        await rollback();
        return NextResponse.json({ error: result.error }, { status: result.conflict ? 409 : 503 });
      }
      if (result.acquired || result.previousBooking) reserved.push({ type, date, time, reservationId: result.reservationId, previousBooking: result.previousBooking });
    }
    // An active appointment cannot move back into the pre-booking queues.
    // Older editors can send a stale New/Contacted status with a reschedule.
    // Also repair early-stage records whose booking already exists, including
    // selected additional visits and saves that only change the end time.
    const intakeStatuses = new Set(["New", "New Lead", "Contacted", "Waiting for Info", "Waiting for Information", "Pending Info"]);
    for (const type of ["inspection", "job"] as const) {
      const field = type === "job" ? "jobAt" : "inspectionAt";
      if (!body[field] || /^(lost|cancelled|closed|no response)/i.test(body.status || primary.status || "")) continue;
      if (intakeStatuses.has(body.status)) {
        body.status = statusAfterBooking(type, primary.status) || primary.status;
      } else if (!body.status || body.status === primary.status) {
        body.status = statusAfterBooking(type, body.status || primary.status) || body.status;
      }
    }
    const persisted = { ...body };
    if (bookingType && primary[bookingType === "job" ? "jobAt" : "inspectionAt"] &&
        (appendBooking || secondaryVisit)) {
      const keys = bookingType === "job" ? ["jobAt", "jobEndAt", "jobWorkSegments", "technician", "technicianId", "technicianUsername"]
        : ["inspectionAt", "inspectionEndAt", "inspectionWorkSegments", "assigned", "inspectorId", "inspectorUsername"];
      for (const key of keys) delete persisted[key];
    }
    const ok = await updateSubmission(id, persisted);
    if (!ok) {
      await rollback();
      return NextResponse.json({ error: "Update failed." }, { status: 400 });
    }
  } catch (err) {
    await rollback();
    console.error("Update appointment failed:", err);
    return NextResponse.json({ error: "Could not save changes." }, { status: 500 });
  }

  for (const type of ["inspection", "job"] as const) {
    const field = type === "job" ? "jobAt" : "inspectionAt";
    const old = before[field]?.slice(0, 16);
    if (!appendBooking && old && field in body && body[field]?.slice(0, 16) !== old) {
      await releaseBookingSlot(id, type, old.slice(0, 10), old.slice(11, 16), { bookingId: selectedBookingId || primary.bookings?.find(b => b.type === type && isPrimaryBooking(primary, b))?.bookingId });
    }
  }

  // Automatic step: write an audit-trail entry for meaningful staff changes.
  if (before) {
    const session = await verifySession(req.cookies.get(SESSION_COOKIE)?.value);
    const actor = session?.username || "staff";
    const now = new Date().toISOString();
    if (typeof body.status === "string" && body.status !== before.status) {
      await appendActivity(id, {
        time: now,
        actor,
        action: "Status changed",
        detail: `${before.status} → ${body.status}`,
      });


      // ── Transition automations (auto-invoice / auto-warranty) ──
      // Best-effort; each helper is internally guarded and idempotent.
      if (body.status === "Job Done") {
        // Invoice is no longer auto-sent — Finance (Login 3) issues it manually.
        await sendInternalAlert({
          title: "Job completed",
          emoji: "🧾",
          accent: "#001f97",
          lines: [
            `${before.name || "A customer"} — ${before.address || ""}`.trim(),
            `Job is completed. Please review and send the invoice manually.`,
          ],
          leadId: id,
        });
      } else if (body.status === "Payment Received") {
        // Warranty is NOT auto-sent — Finance (Login 3) issues it manually.
        await sendInternalAlert({
          title: "Payment received",
          emoji: "💰",
          accent: "#16a34a",
          lines: [
            `${before.name || "A customer"}${before.quoteAmount ? ` — AUD $${before.quoteAmount.toFixed(2)}` : ""}`,
            `Send the 10-year warranty from the CRM when ready.`,
          ],
          leadId: id,
        });
      }
    }
    if (typeof body.assigned === "string" && body.assigned !== before.assigned) {
      await appendActivity(id, {
        time: now,
        actor,
        action: "Reassigned",
        detail: body.assigned,
      });

      // Email the newly assigned staff member their lead details
      if (body.assigned && isEmailConfigured()) {
        try {
          const staffMember = await getStaffMemberByUsername(body.assigned);
          if (staffMember?.email) {
            const logoUrl = await getEmailLogoUrl();
            const lead = before;
            const rows: string[] = [];
            if (lead.name) rows.push(`<p><b>Customer:</b> ${lead.name}</p>`);
            if (lead.address) rows.push(`<p><b>Address:</b> ${lead.address}</p>`);
            if (lead.phone) rows.push(`<p><b>Phone:</b> ${lead.phone}</p>`);
            if (lead.service) rows.push(`<p><b>Service:</b> ${lead.service}</p>`);
            if (lead.status) rows.push(`<p><b>Status:</b> ${lead.status}</p>`);
            if (lead.inspectionAt) {
              rows.push(`<p><b>Inspection:</b> ${formatAppt(lead.inspectionAt, { weekday: "long", day: "2-digit", month: "short", year: "numeric", hour: "numeric", minute: "2-digit", hour12: true }) || lead.inspectionAt}</p>`);
            }
            await sendEmail({
              toEmail: staffMember.email,
              subject: `New lead assigned to you${lead.address ? ` — ${lead.address}` : ""}`,
              html: wrapEmailHtml(
                `<h2 style="margin:0 0 12px">You've been assigned a lead</h2>
                 <p>Hi ${staffMember.name || staffMember.username}, a new lead has been assigned to you:</p>
                 ${rows.join("\n")}
                 <p style="margin-top:16px;color:#64748b">Please log in to the CRM to review all details and take action.</p>`,
                "New Groutix lead assigned",
                logoUrl
              ),
            });
          }
        } catch (err) {
          console.error("Staff assignment email failed (non-fatal):", err);
        }
      }
    }

    // Field-technician dispatch: log it, and email the technician the job
    // details so they know where to go. Best-effort — never blocks the save.
    if (typeof body.technician === "string" && body.technician !== (before.technician || "")) {
      await appendActivity(id, {
        time: now,
        actor,
        action: body.technician ? "Technician assigned" : "Technician unassigned",
        detail: body.technician || undefined,
      });
      if (body.technician && typeof body.technicianId === "string" && body.technicianId) {
        await notifyTechnicianAssigned(body.technicianId, { ...before, ...body }).catch((err) =>
          console.error("notifyTechnicianAssigned failed (non-fatal):", err)
        );
      }
    }
    if (typeof body.contacted === "string" && body.contacted && body.contacted !== before.contacted) {
      await appendActivity(id, { time: now, actor, action: "Marked contacted" });
    }

    // ── Keep bookings collection in lockstep with manual staff changes ──
    if (body.status === "Lost" || body.status === "Cancelled") {
      await deleteBooking(id);
    } else {
      if (typeof body.inspectionAt === "string" && (body.inspectionAt !== (normalizeApptString(before.inspectionAt) || "") || body.inspectionEndAt !== undefined && (body.inspectionEndAt || "") !== (before.inspectionEndAt || ""))) {
        if (body.inspectionAt.includes("T")) {
          // Reservation was committed before saving the lead.

          // Reschedule: notify customer when an existing booking is moved.
          if (before.inspectionAt) {
            if (!before.email || !isEmailConfigured()) notificationWarnings.push("Rescheduling email not sent: email address or service unavailable.");
            if (!before.phone || !isSmsConfigured()) notificationWarnings.push("Rescheduling SMS not sent: phone number or service unavailable.");
            await updateSubmission(id, { inspectionRescheduled: true });
            await appendActivity(id, {
              time: now,
              actor,
              action: "Inspection rescheduled",
              detail: `${formatAppt(before.inspectionAt, { weekday: "short", day: "numeric", month: "short", year: "numeric", hour: "numeric", minute: "2-digit", hour12: true }) || before.inspectionAt} → ${formatAppt(body.inspectionAt, { weekday: "short", day: "numeric", month: "short", year: "numeric", hour: "numeric", minute: "2-digit", hour12: true }) || body.inspectionAt}`,
            });

            let newDateLabel = formatAppt(body.inspectionAt, {
              weekday: "long", day: "2-digit", month: "short",
              year: "numeric", hour: "numeric", minute: "2-digit", hour12: true,
            }) || body.inspectionAt;
            if (body.inspectionEndAt) newDateLabel += ` – ${body.inspectionEndAt.replace("T", " ")} (Melbourne time)`;
            const firstName = before.name?.trim().split(/\s+/)[0] || "there";
            const propertyAddress = before.address || "your property";

            if (isEmailConfigured() && before.email) {
              const logoUrl = await getEmailLogoUrl();
              await sendEmail({
                toEmail: before.email,
                subject: "Your Groutix Inspection Has Been Rescheduled",
                html: wrapEmailHtml(
                  `<h2 style="margin:0 0 12px">Inspection Rescheduled</h2>
                   <p>Hi ${firstName},</p>
                   <p>Your on-site inspection at <strong>${propertyAddress}</strong> has been rescheduled to:</p>
                   <p style="font-size:16px;font-weight:bold;color:#001f97;margin:12px 0">&#128197; ${newDateLabel}</p>
                   <p>If you have any questions or need to reschedule again, please reply to this email, visit <a href="https://groutix.com" target="_blank" style="color:#001f97;font-weight:700;text-decoration:underline;">groutix.com</a>, or call us on <a href="tel:+61370238094" style="color:#001f97;font-weight:700;text-decoration:none;">(03) 7023 8094</a>.</p>
                   <p>Kind regards,<br>Groutix Team</p>`,
                  "Your Groutix inspection has been rescheduled",
                  logoUrl
                ),
              }).catch(() => { notificationWarnings.push("Rescheduling email failed. Send it from the customer messages panel."); });
            }

            if (isSmsConfigured() && before.phone) {
              const shortLabel = formatAppt(body.inspectionAt, {
                weekday: "short", day: "numeric", month: "short",
                hour: "numeric", minute: "2-digit", hour12: true,
              }) || body.inspectionAt;
              const smsBody = prepareSinglePartSms(
                `Your Groutix inspection has been rescheduled to ${shortLabel}${body.inspectionEndAt ? ` to ${body.inspectionEndAt.replace("T", " ")}` : ""}. Call (03) 7023 8094 for questions.`
              );
              const result = await sendSms({ to: before.phone, body: smsBody, campaign: "inspection_reschedule" }).catch(() => ({ ok: false }));
              if (!result.ok) notificationWarnings.push("Rescheduling SMS failed. Send it from the customer messages panel.");
            }
          } else {
            // Brand-new inspection booking — log it
            await appendActivity(id, {
              time: now,
              actor,
              action: "Inspection booked",
              detail: formatAppt(body.inspectionAt, { weekday: "short", day: "numeric", month: "short", year: "numeric", hour: "numeric", minute: "2-digit", hour12: true }) || body.inspectionAt,
            });
          }
        } else if (body.inspectionAt === "" || !body.inspectionAt) {
          // The selected inspection was released above; sibling visits remain.
          if (before.inspectionAt) {
            await appendActivity(id, { time: now, actor, action: "Inspection booking cleared", detail: before.inspectionAt });
          }
        }
      }
      if (typeof body.jobAt === "string" && (body.jobAt !== (normalizeApptString(before.jobAt) || "") || body.jobEndAt !== undefined && (body.jobEndAt || "") !== (before.jobEndAt || ""))) {
        if (body.jobAt.includes("T")) {
          // Reservation was committed before saving the lead.

          // Reschedule: notify customer and log activity when an existing job booking is moved.
          if (before.jobAt) {
            if (!before.email || !isEmailConfigured()) notificationWarnings.push("Rescheduling email not sent: email address or service unavailable.");
            if (!before.phone || !isSmsConfigured()) notificationWarnings.push("Rescheduling SMS not sent: phone number or service unavailable.");
            await appendActivity(id, {
              time: now,
              actor,
              action: "Job rescheduled",
              detail: `${formatAppt(before.jobAt, { weekday: "short", day: "numeric", month: "short", year: "numeric", hour: "numeric", minute: "2-digit", hour12: true }) || before.jobAt} → ${formatAppt(body.jobAt, { weekday: "short", day: "numeric", month: "short", year: "numeric", hour: "numeric", minute: "2-digit", hour12: true }) || body.jobAt}`,
            });

            let newJobDateLabel = formatAppt(body.jobAt, {
              weekday: "long", day: "2-digit", month: "short",
              year: "numeric", hour: "numeric", minute: "2-digit", hour12: true,
            }) || body.jobAt;
            if (body.jobEndAt) newJobDateLabel += ` – ${body.jobEndAt.replace("T", " ")} (Melbourne time)`;
            const firstName = before.name?.trim().split(/\s+/)[0] || "there";
            const propertyAddress = before.address || "your property";

            if (isEmailConfigured() && before.email) {
              const logoUrl = await getEmailLogoUrl();
              await sendEmail({
                toEmail: before.email,
                subject: "Your Groutix Job Has Been Rescheduled",
                html: wrapEmailHtml(
                  `<h2 style="margin:0 0 12px">Job Rescheduled</h2>
                   <p>Hi ${firstName},</p>
                   <p>Your grouting job at <strong>${propertyAddress}</strong> has been rescheduled to:</p>
                   <p style="font-size:16px;font-weight:bold;color:#001f97;margin:12px 0">&#128197; ${newJobDateLabel}</p>
                   <p>If you have any questions or need to reschedule again, please reply to this email, visit <a href="https://groutix.com" target="_blank" style="color:#001f97;font-weight:700;text-decoration:underline;">groutix.com</a>, or call us on <a href="tel:+61370238094" style="color:#001f97;font-weight:700;text-decoration:none;">(03) 7023 8094</a>.</p>
                   <p>Kind regards,<br>Groutix Team</p>`,
                  "Your Groutix job has been rescheduled",
                  logoUrl
                ),
              }).catch(() => { notificationWarnings.push("Rescheduling email failed. Send it from the customer messages panel."); });
            }

            if (isSmsConfigured() && before.phone) {
              const shortJobLabel = formatAppt(body.jobAt, {
                weekday: "short", day: "numeric", month: "short",
                hour: "numeric", minute: "2-digit", hour12: true,
              }) || body.jobAt;
              const smsBody = prepareSinglePartSms(
                `Your Groutix job has been rescheduled to ${shortJobLabel}${body.jobEndAt ? ` to ${body.jobEndAt.replace("T", " ")}` : ""}. Call (03) 7023 8094 for questions.`
              );
              const result = await sendSms({ to: before.phone, body: smsBody, campaign: "job_reschedule" }).catch(() => ({ ok: false }));
              if (!result.ok) notificationWarnings.push("Rescheduling SMS failed. Send it from the customer messages panel.");
            }
          } else {
            // Brand-new job booking (no previous jobAt) — log it
            await appendActivity(id, {
              time: now,
              actor,
              action: "Job booked",
              detail: formatAppt(body.jobAt, { weekday: "short", day: "numeric", month: "short", year: "numeric", hour: "numeric", minute: "2-digit", hour12: true }) || body.jobAt,
            });
          }
        } else if (body.jobAt === "" || !body.jobAt) {
          // The selected job was released above; sibling visits remain.
          if (before.jobAt) {
            await appendActivity(id, { time: now, actor, action: "Job booking cleared", detail: before.jobAt });
          }
        }
      }
    }
  }

  if (bookingNotifications) {
    const customer = { ...before, ...body };
    for (const type of ["inspection", "job"] as const) {
      const field = type === "inspection" ? "inspectionAt" : "jobAt";
      // Existing appointments have their own reschedule notifications above.
      if (!body[field] || before[field] || ["Lost", "Cancelled"].includes(customer.status)) continue;
      let when = formatAppt(body[field], { weekday: "long", day: "numeric", month: "short", year: "numeric", hour: "numeric", minute: "2-digit", hour12: true }) || body[field];
      const end = customer[type === "job" ? "jobEndAt" : "inspectionEndAt"];
      if (end) when += ` – ${end.replace("T", " ")}`;
      const escape = (value: string) => value.replace(/[&<>"']/g, ch => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[ch]!));
      if (customer.email && isEmailConfigured()) {
        try {
          await sendEmail({ toEmail: customer.email, subject: `Your Groutix ${type} is confirmed`,
            html: wrapEmailHtml(`<h2>Booking confirmed</h2><p>Hi ${escape(customer.name || "there")},</p><p>Your ${type} is booked for <strong>${escape(when)}</strong> (Melbourne time).</p><p>Address: ${escape(customer.address || "your property")}</p><p>Service: ${escape(customer.service || "Tile and grout service")}</p><p>Call (03) 7023 8094 if you need to make changes.</p>`, "Your booking is confirmed", await getEmailLogoUrl()) });
        } catch { notificationWarnings.push("Confirmation email failed. Send it from the customer messages panel."); }
      } else notificationWarnings.push("Confirmation email not sent: email address or email service unavailable.");
      if (customer.phone && isSmsConfigured()) {
        try {
          const result = await sendSms({ to: customer.phone, body: prepareSinglePartSms(`Groutix: Your ${type} is confirmed for ${when} (Melbourne time). Call (03) 7023 8094 for changes.`), campaign: `${type}_confirmation` });
          if (!result.ok) notificationWarnings.push("Confirmation SMS failed. Send it from the customer messages panel.");
        } catch { notificationWarnings.push("Confirmation SMS failed. Send it from the customer messages panel."); }
      } else notificationWarnings.push("Confirmation SMS not sent: phone number or SMS service unavailable.");
    }
  }
  return NextResponse.json({ ok: true, notificationWarnings, item: await getSubmission(id) });
}

export async function DELETE(_req: NextRequest, { params }: Ctx) {
  if (!isMongoConfigured()) {
    return NextResponse.json({ error: "Database is not configured." }, { status: 503 });
  }
  const { id } = await params;
  // Identify who is deleting for recycle bin audit trail
  let deletedBy = "system";
  const token = _req.cookies.get(SESSION_COOKIE)?.value;
  if (token) {
    const session = await verifySession(token);
    if (session?.username) deletedBy = session.username;
  }
  const ok = await deleteSubmission(id, deletedBy);
  if (!ok) return NextResponse.json({ error: "Not found." }, { status: 404 });
  await deleteBooking(id);
  return NextResponse.json({ ok: true });
}
